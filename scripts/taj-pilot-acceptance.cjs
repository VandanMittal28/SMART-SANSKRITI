// Run against a local production build. PLAYWRIGHT_MODULE_PATH may point to a bundled Playwright installation.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve('output/taj-pilot');
fs.mkdirSync(output,{recursive:true});
(async () => {
 const browser = await chromium.launch({headless:true,slowMo:100});
 const context = await browser.newContext({viewport:{width:1440,height:1080},recordVideo:{dir:output,size:{width:1440,height:1080}}});
 const page = await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TAJ_PILOT_URL || 'http://127.0.0.1:3100/taj-pilot');
 await page.getByRole('button',{name:'Normal',exact:true}).waitFor();
 await page.evaluate(()=>localStorage.setItem('real-records-sentinel','untouched'));
 const click = async name => (['Normal','Rising queue','Congestion','Recovery','Offline','Reset'].includes(name) ? page.getByRole('group',{name:'Scenario player'}) : page).getByRole('button',{name,exact:true}).click();
 const run = async () => {
   await click('Reset'); await click('Normal'); await click('Rising queue');
   assert.equal(await page.getByRole('button',{name:'Assign simulated staff'}).count(),0);
   await click('Congestion'); await click('Assign simulated staff'); await click('Acknowledge');
   await page.getByLabel('Action / resolution note').fill('Opened simulated queue lane'); await click('Record action');
   await click('Generate East Gate preview');
   assert.match(await page.locator('[lang="hi"]').innerText(),/कृपया/);
   await page.screenshot({path:path.join(output,'congestion-preview.png'),fullPage:true});
   await click('Recovery');
   assert.match(await page.getByRole('region',{name:'Staff cases'}).innerText(),/action-recorded/);
   await page.getByLabel('Action / resolution note').fill('Recovery verified'); await click('Resolve with note');
   await page.getByText('History (5)',{exact:true}).click();
   const history = await page.getByRole('region',{name:'Staff cases'}).locator('ol').innerText();
   await page.reload(); await page.getByText('History (5)',{exact:true}).click();
   assert.equal(await page.getByRole('region',{name:'Staff cases'}).locator('ol').innerText(),history);
   await click('Offline');
   assert.match(await page.getByRole('region',{name:'Visitor advisory preview'}).innerText(),/suppressed/);
   await click('Real-world readiness');
   assert.equal(await page.getByText('Unknown · source unavailable',{exact:true}).count(),3);
   assert.equal(await page.getByRole('button',{name:'Reset',exact:true}).count(),0);
   assert.equal(await page.getByRole('button',{name:'Real staff actions unavailable'}).isDisabled(),true);
   await page.screenshot({path:path.join(output,'real-readiness.png'),fullPage:true});
   await click('Demo workspace'); await click('Reset');
   assert.match(await page.locator('body').innerText(),/No cases yet/);
   assert.equal(await page.evaluate(()=>localStorage.getItem('real-records-sentinel')),'untouched');
   return history;
 };
 assert.equal(await run(),await run());
 await click('Generate East Gate preview');
 for(let i=0;i<3;i++) await click('Advance 10 seconds');
 assert.match(await page.getByRole('region',{name:'Visitor advisory preview'}).innerText(),/expired/);
 // Denied browser writes must show an error, with no applied scenario.
 await page.evaluate(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=()=>{throw new Error('Test write denial')}});
 await click('Congestion'); await page.locator('main').getByRole('alert').waitFor();
 assert.match(await page.locator('main').getByRole('alert').innerText(),/could not be saved/);
 assert.equal(await page.getByRole('button',{name:'Assign simulated staff'}).count(),0);
 await page.evaluate(()=>{Storage.prototype.setItem=window.originalSetItem});
 await click('Reset'); await click('Congestion'); await click('Generate East Gate preview');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'mobile-preview.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 // Corrupt demo records must never silently reset on load.
 await page.evaluate(()=>localStorage.setItem('sanskriti: taj-pilot:demo:v1','corrupt'));
 await page.reload(); await page.locator('main').getByRole('alert').waitFor();
 assert.match(await page.locator('main').getByRole('alert').innerText(),/not been overwritten/);
 await click('Reset saved demo only'); await page.getByRole('button',{name:'Normal',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('real-records-sentinel')),'untouched');
 assert.deepEqual(errors,[]);
 const video = page.video(); await context.close();
 await video.saveAs(path.join(output,'taj-pilot-demo.webm'));
 await browser.close();
 const result={status:'passed',journeyRuns:2,checks:['identical scenario history','saved state after reload','bilingual preview','expiry','Unknown suppression','real-mode isolation','demo-only reset','failed-write rollback','corrupt-store recovery','mobile layout','no browser errors']};
 fs.writeFileSync(path.join(output,'acceptance-results.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exit(1)});
