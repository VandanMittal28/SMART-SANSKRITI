// Compile only the ported mobile screens; keep the website's layout isolated.
import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
const base = path.resolve(import.meta.dirname, '..');
const input = `@import "tailwindcss" source(none);\n@source "../components/explore";\n@source "../components/original";\n@source "../components/ui/spinner.tsx";`;
const result = await postcss([tailwind({base})]).process(input, {from:path.join(base,'styles/mobile-input.css')});
const root = postcss.parse(result.css);
root.walkRules(rule => {
 if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
 rule.selectors = rule.selectors.map(s => s.includes(':root') || s === ':host' ? '.sanskriti-original' : `.sanskriti-original ${s}`);
});
// Unwrap cascade layers: original website styles are intentionally unlayered.
root.walkAtRules('layer', rule => {if(rule.nodes) rule.replaceWith(...rule.nodes);else rule.remove()});
await fs.writeFile(path.join(base,'styles/mobile-utilities.css'), '/* Generated by scripts/build-mobile-styles.mjs */\n'+root.toString());
